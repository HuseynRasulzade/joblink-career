// Builds lib/world-skills-data.ts: the software and tools that the US O*NET
// database (CC BY 4.0, https://www.onetcenter.org) lists for occupations, the
// way LinkedIn-style skill lists name them ("Tableau", "Atlassian JIRA").
// They are offered next to the ESCO skills in the skill picker and accepted
// when saved; they are not part of the curated matching catalog.
//   node --experimental-strip-types scripts/build-world-skills.mjs
import { writeFileSync } from "node:fs";
import { canonicalSkill, normalizeSkillKey } from "../lib/skill-catalog.ts";

const URL_ = "https://www.onetcenter.org/dl_files/database/db_29_0_text/Technology%20Skills.txt";
const text = await (await fetch(URL_, { headers: { "User-Agent": "Mozilla/5.0" } })).text();
const names = new Map();
for (const [i, line] of text.split("\n").entries()) {
  if (!i) continue;
  const cols = line.split("\t");
  const name = (cols[1] || "").replace(/\s+/g, " ").trim();
  if (name.length < 2 || name.length > 60) continue;
  const key = normalizeSkillKey(name);
  if (!key || canonicalSkill(name) || names.has(key)) continue;
  names.set(key, name);
}
const list = [...names.values()].sort((a, b) => a.localeCompare(b, "en"));
writeFileSync(
  new URL("../lib/world-skills-data.ts", import.meta.url),
  `// Generated by scripts/build-world-skills.mjs from O*NET (CC BY 4.0). Do not edit by hand.\nexport const WORLD_SKILLS: string[] = ${JSON.stringify(list)};\n`,
);
console.log(`${list.length} tools and technologies`);
