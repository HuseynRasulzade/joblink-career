// Builds lib/skill-catalog-data.ts from data/skills/*.txt.
//   node --experimental-strip-types scripts/build-skills.mjs
// Rows: category|English|Azərbaycanca|alias;alias   (aliases optional, Russian ones go here too)
// A skill whose name already exists in the base catalog or an earlier row is skipped;
// an alias that already belongs to another skill is dropped from this one.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { BASE_SKILL_CATALOG, ENGLISH_CATEGORIES, normalizeSkillKey } from "../lib/skill-catalog.ts";

const dir = new URL("../data/skills/", import.meta.url);
const key = normalizeSkillKey;
const slug = (en) => en.toLowerCase().replace(/&/g, " and ").replace(/\+/g, "p").replace(/#/g, "sharp").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const owner = new Map();
for (const s of BASE_SKILL_CATALOG) for (const a of s.aliases) owner.set(key(a), s.id);
const ids = new Set(BASE_SKILL_CATALOG.map((s) => s.id));
const rows = [];
const skipped = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) {
  for (const [n, raw] of readFileSync(new URL(file, dir), "utf8").split("\n").entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const where = `${file}:${n + 1}`;
    const [category, en, az, extra = ""] = line.split("|").map((x) => x.trim());
    if (!ENGLISH_CATEGORIES[category] || !en || !az) {
      skipped.push(`${where} malformed: ${line}`);
      continue;
    }
    let id = slug(en);
    if (!id) id = slug(az);
    const taken = [az, en].map((l) => owner.get(key(l))).find(Boolean);
    if (ids.has(id) || taken) {
      skipped.push(`${where} duplicate of ${taken || id}: ${en}`);
      continue;
    }
    ids.add(id);
    const aliases = [];
    for (const a of extra.split(";").map((x) => x.trim()).filter(Boolean)) {
      if (!owner.has(key(a)) && !aliases.some((x) => key(x) === key(a))) aliases.push(a);
    }
    for (const l of [az, en, ...aliases]) if (!owner.has(key(l))) owner.set(key(l), id);
    rows.push({ category, id, az, en, aliases });
  }
}

const q = JSON.stringify;
const out = `// Generated by scripts/build-skills.mjs from data/skills. Do not edit by hand.
import type { SkillDefinition } from "./skill-catalog.ts";

const s = (category: string, categoryEn: string, id: string, label: string, labelEn: string, aliases: string[] = []): SkillDefinition => ({
  id,
  label,
  labelEn,
  category,
  categoryEn,
  aliases: [label, labelEn, ...aliases],
});

export const EXTRA_SKILLS: SkillDefinition[] = [
${rows.map((r) => `  s(${q(r.category)}, ${q(ENGLISH_CATEGORIES[r.category])}, ${q(r.id)}, ${q(r.az)}, ${q(r.en)}${r.aliases.length ? `, ${q(r.aliases)}` : ""}),`).join("\n")}
];
`;
writeFileSync(new URL("../lib/skill-catalog-data.ts", import.meta.url), out);
console.log(`${rows.length} skills, ${skipped.length} skipped`);
for (const x of skipped) console.log("  skipped:", x);
