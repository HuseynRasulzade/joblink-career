// Builds lib/major-catalog-data.ts from data/majors/*.txt.
//   node --experimental-strip-types scripts/build-majors.mjs
// Rows: field|English|Azərbaycanca|Русский|alias;alias   (aliases optional)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { MAJOR_FIELDS, normalizeMajorKey } from "../lib/major-catalog.ts";

const dir = new URL("../data/majors/", import.meta.url);
const key = normalizeMajorKey;
const slug = (en) => en.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const owner = new Map();
const ids = new Set();
const rows = [];
const skipped = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) {
  for (const [n, raw] of readFileSync(new URL(file, dir), "utf8").split("\n").entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const where = `${file}:${n + 1}`;
    const [field, en, az, ru, extra = ""] = line.split("|").map((x) => x.trim());
    if (!MAJOR_FIELDS[field] || !en || !az || !ru) {
      skipped.push(`${where} malformed: ${line}`);
      continue;
    }
    const id = slug(en);
    const taken = [az, en, ru].map((l) => owner.get(key(l))).find(Boolean);
    if (ids.has(id) || taken) {
      skipped.push(`${where} duplicate of ${taken || id}: ${en}`);
      continue;
    }
    ids.add(id);
    const aliases = [];
    for (const a of extra.split(";").map((x) => x.trim()).filter(Boolean)) {
      if (!owner.has(key(a)) && !aliases.some((x) => key(x) === key(a))) aliases.push(a);
    }
    for (const l of [az, en, ru, ...aliases]) if (!owner.has(key(l))) owner.set(key(l), id);
    rows.push({ field, id, az, en, ru, aliases });
  }
}
const q = JSON.stringify;
const out = `// Generated by scripts/build-majors.mjs from data/majors. Do not edit by hand.
import type { Major } from "./major-catalog.ts";

const m = (field: string, id: string, label: string, labelEn: string, labelRu: string, aliases: string[] = []): Major => ({
  id,
  label,
  labelEn,
  labelRu,
  field,
  aliases: [label, labelEn, labelRu, ...aliases],
});

export const MAJOR_DATA: Major[] = [
${rows.map((r) => `  m(${q(r.field)}, ${q(r.id)}, ${q(r.az)}, ${q(r.en)}, ${q(r.ru)}${r.aliases.length ? `, ${q(r.aliases)}` : ""}),`).join("\n")}
];
`;
writeFileSync(new URL("../lib/major-catalog-data.ts", import.meta.url), out);
console.log(`${rows.length} programmes, ${skipped.length} skipped`);
for (const s of skipped) console.log("  skipped:", s);
