// Builds lib/university-catalog-data.ts from data/universities/*.txt.
//   node --experimental-strip-types scripts/build-universities.mjs
// Rows: COUNTRY|English|Azərbaycanca|Русский|alias;alias   (aliases optional)
// A row whose name already belongs to another university is skipped.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { COUNTRIES, normalizeUniversityKey } from "../lib/university-catalog.ts";

const dir = new URL("../data/universities/", import.meta.url);
const key = normalizeUniversityKey;
const slug = (en) => en.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const owner = new Map();
const ids = new Set();
const rows = [];
const skipped = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) {
  for (const [n, raw] of readFileSync(new URL(file, dir), "utf8").split("\n").entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const where = `${file}:${n + 1}`;
    const [country, en, az, ru, extra = ""] = line.split("|").map((x) => x.trim());
    if (!COUNTRIES[country] || !en || !az || !ru) {
      skipped.push(`${where} malformed: ${line}`);
      continue;
    }
    const id = `${country.toLowerCase()}-${slug(en)}`;
    const taken = [az, en, ru].map((l) => owner.get(key(l))).find(Boolean);
    if (ids.has(id) || taken) {
      skipped.push(`${where} duplicate of ${taken || id}: ${en}`);
      continue;
    }
    ids.add(id);
    const aliases = [];
    for (const a of extra.split(";").map((x) => x.trim()).filter(Boolean)) {
      if (!owner.has(key(a)) && !aliases.some((x) => key(x) === key(a))) aliases.push(a);
    }
    for (const l of [az, en, ru, ...aliases]) if (!owner.has(key(l))) owner.set(key(l), id);
    rows.push({ country, id, az, en, ru, aliases });
  }
}

const q = JSON.stringify;
const out = `// Generated by scripts/build-universities.mjs from data/universities. Do not edit by hand.
import type { University } from "./university-catalog.ts";

const u = (country: string, id: string, label: string, labelEn: string, labelRu: string, aliases: string[] = []): University => ({
  id,
  label,
  labelEn,
  labelRu,
  country,
  aliases: [label, labelEn, labelRu, ...aliases],
});

export const UNIVERSITY_DATA: University[] = [
${rows.map((r) => `  u(${q(r.country)}, ${q(r.id)}, ${q(r.az)}, ${q(r.en)}, ${q(r.ru)}${r.aliases.length ? `, ${q(r.aliases)}` : ""}),`).join("\n")}
];
`;
writeFileSync(new URL("../lib/university-catalog-data.ts", import.meta.url), out);
console.log(`${rows.length} universities, ${skipped.length} skipped`);
for (const s of skipped) console.log("  skipped:", s);
