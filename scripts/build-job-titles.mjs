// Builds lib/job-title-catalog-extra.ts from data/job-titles/*.txt.
//   node --experimental-strip-types scripts/build-job-titles.mjs
// Rows: family|English|Azərbaycanca|Русский|alias;alias   (aliases optional)
// Lines starting with "=" give a Russian label for a hand-written title: =id|Русский
// Seniority variants (Junior/Senior/Lead/Head of) are generated at runtime and must
// not be listed. A row whose label already belongs to another title is skipped.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { BASE_JOB_TITLES, JOB_TITLE_FAMILIES, normalizeJobTitleKey } from "../lib/job-title-catalog.ts";

const dir = new URL("../data/job-titles/", import.meta.url);
const key = normalizeJobTitleKey;
const slug = (en) => en.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const owner = new Map();
const ids = new Set();
for (const t of BASE_JOB_TITLES) {
  ids.add(t.id);
  for (const a of t.aliases) if (!owner.has(key(a))) owner.set(key(a), t.id);
}

const rows = [];
const ru = {};
const skipped = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) {
  for (const [n, raw] of readFileSync(new URL(file, dir), "utf8").split("\n").entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const where = `${file}:${n + 1}`;
    if (line.startsWith("=")) {
      const [id, label] = line.slice(1).split("|").map((x) => x.trim());
      if (!ids.has(id) || !label) skipped.push(`${where} unknown base id ${id}`);
      else ru[id] = label;
      continue;
    }
    const [family, en, az, rus, extra = ""] = line.split("|").map((x) => x.trim());
    if (!JOB_TITLE_FAMILIES[family] || !en || !az || !rus) {
      skipped.push(`${where} malformed: ${line}`);
      continue;
    }
    const id = slug(en);
    const taken = [az, en, rus].map((l) => owner.get(key(l))).find(Boolean);
    if (ids.has(id) || taken) {
      skipped.push(`${where} duplicate of ${taken || id}: ${en}`);
      continue;
    }
    ids.add(id);
    const aliases = [];
    for (const a of extra.split(";").map((x) => x.trim()).filter(Boolean)) {
      if (!owner.has(key(a)) && !aliases.some((x) => key(x) === key(a))) aliases.push(a);
    }
    for (const l of [az, en, rus, ...aliases]) if (!owner.has(key(l))) owner.set(key(l), id);
    rows.push({ family, id, az, en, rus, aliases });
  }
}

const q = JSON.stringify;
const out = `// Generated by scripts/build-job-titles.mjs from data/job-titles. Do not edit by hand.
import type { JobTitleDefinition } from "./job-title-catalog.ts";

const t = (family: string, id: string, label: string, labelEn: string, labelRu: string, aliases: string[] = []): JobTitleDefinition => ({
  id,
  label,
  labelEn,
  labelRu,
  family,
  aliases: [label, labelEn, labelRu, ...aliases],
});

export const RU_LABELS_OF_BASE: Record<string, string> = ${q(ru, null, 2)};

export const EXTRA_JOB_TITLES: JobTitleDefinition[] = [
${rows.map((r) => `  t(${q(r.family)}, ${q(r.id)}, ${q(r.az)}, ${q(r.en)}, ${q(r.rus)}${r.aliases.length ? `, ${q(r.aliases)}` : ""}),`).join("\n")}
];
`;
writeFileSync(new URL("../lib/job-title-catalog-extra.ts", import.meta.url), out);
console.log(`${rows.length} titles, ${Object.keys(ru).length} Russian labels for base titles, ${skipped.length} skipped`);
for (const s of skipped) console.log("  skipped:", s);
